/**
 * @typedef {Record<string, string | string[]>} PosLexicon
 * @typedef {Object} LexiconBuildOptions
 * @property {boolean} [includeProperNouns]
 * @property {number} [minimumTokenLength]
 */

const DEFAULT_ALLOWED_POS_PREFIXES = Object.freeze([
  'CC',
  'CD',
  'DT',
  'EX',
  'FW',
  'IN',
  'JJ',
  'MD',
  'NN',
  'PDT',
  'PRP',
  'RB',
  'RP',
  'TO',
  'UH',
  'VB',
  'WDT',
  'WP',
  'WRB'
]);

const DEFAULT_EXCLUDED_POS_PREFIXES = Object.freeze([
  'NNP',
  'NNPS',
  '"',
  ',',
  '.',
  ':',
  '(',
  ')'
]);

/**
 * Returns POS tags in a normalized array.
 *
 * @param {string | string[] | null | undefined} value
 * @returns {string[]}
 */
export function normalizeEnglishLexiconPosTags(value) {
  if (Array.isArray(value)) {
    return value.map((tag) => String(tag || '').trim()).filter(Boolean);
  }
  return String(value || '')
    .split('|')
    .map((tag) => tag.trim())
    .filter(Boolean);
}

/**
 * Normalizes one lexicon word for spelling lookup.
 *
 * @param {string} word
 * @returns {string}
 */
export function normalizeEnglishLexiconWordForAsset(word) {
  return String(word || '')
    .trim()
    .replace(/\\\//g, '/')
    .toLowerCase();
}

/**
 * Returns true when a word shape is useful for ontology spelling QA.
 *
 * @param {string} word
 * @param {LexiconBuildOptions} [options]
 * @returns {boolean}
 */
export function shouldKeepEnglishLexiconWordShape(word, options = {}) {
  const minimumTokenLength = Number.isInteger(options.minimumTokenLength)
    ? Number(options.minimumTokenLength)
    : 2;
  const value = normalizeEnglishLexiconWordForAsset(word);
  if (value.length < minimumTokenLength) {
    return value === 'a' || value === 'i';
  }
  if (!/[a-z]/.test(value)) {
    return false;
  }
  if (/^[^a-z0-9]+$/i.test(value)) {
    return false;
  }
  if (value.includes('/')) {
    return false;
  }
  if (!/^[a-z][a-z0-9]*(?:[-'][a-z0-9]+)*$/.test(value)) {
    return false;
  }
  return true;
}

/**
 * Returns true when the POS tags should be retained.
 *
 * @param {string[]} tags
 * @param {LexiconBuildOptions} [options]
 * @returns {boolean}
 */
export function shouldKeepEnglishLexiconPosTags(tags, options = {}) {
  const normalizedTags = tags.map((tag) => tag.toUpperCase()).filter(Boolean);
  if (!normalizedTags.length) {
    return true;
  }
  if (!options.includeProperNouns && normalizedTags.every((tag) => DEFAULT_EXCLUDED_POS_PREFIXES.includes(tag))) {
    return false;
  }
  return normalizedTags.some((tag) =>
    DEFAULT_ALLOWED_POS_PREFIXES.some((prefix) => tag === prefix || tag.startsWith(prefix))
  );
}

/**
 * Builds sorted spelling words from a POS lexicon.
 *
 * @param {PosLexicon} lexicon
 * @param {LexiconBuildOptions} [options]
 * @returns {string[]}
 */
export function buildEnglishLexiconWordsFromPosLexicon(lexicon, options = {}) {
  const words = new Set();
  for (const [word, tagsValue] of Object.entries(lexicon || {})) {
    const tags = normalizeEnglishLexiconPosTags(tagsValue);
    const normalizedWord = normalizeEnglishLexiconWordForAsset(word);
    if (
      shouldKeepEnglishLexiconWordShape(normalizedWord, options) &&
      shouldKeepEnglishLexiconPosTags(tags, options)
    ) {
      words.add(normalizedWord);
    }
  }
  return Array.from(words).sort((left, right) => left.localeCompare(right));
}

/**
 * Renders an ES module for the generated browser lexicon asset.
 *
 * @param {string[]} words
 * @param {{ sourceLabel?: string }} [options]
 * @returns {string}
 */
export function renderEnglishLexiconAssetModule(words, options = {}) {
  const uniqueWords = Array.from(new Set(words.map(normalizeEnglishLexiconWordForAsset).filter(Boolean)))
    .sort((left, right) => left.localeCompare(right));
  const sourceLabel = options.sourceLabel || 'unknown source';
  return [
    '// docs/app/data/nlp-qa-english-lexicon.js',
    '// @ts-check',
    '// Generated by src/lexicon-build/build-english-lexicon.js.',
    `// Source: ${sourceLabel}`,
    '',
    `export const NLP_QA_ENGLISH_LEXICON_WORDS = Object.freeze(${JSON.stringify(uniqueWords, null, 2)});`,
    ''
  ].join('\n');
}
